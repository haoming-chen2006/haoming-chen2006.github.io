/**
 * Packs the engine's two present sprites into WebP.
 *
 *   node src/room/assets/present/build-present.mjs [--fk=/path/to/FreeKill]
 *
 * A present is not a spritesheet effect, so it is not `build-anim.mjs`'s
 * business. `build-anim.mjs` packs a numbered frame folder into one horizontal
 * strip played with CSS `steps()`; `image/anim/egg` and `image/anim/flower` are
 * not that shape. They are one projectile drawing (`egg.png`) that flies across
 * the table, plus three impact frames (`egg1..3.png`) that land on the target,
 * plus — for the flower — a `star.png` twinkle. `framesOf()` there also parses
 * a frame's index out of its filename, and none of these filenames is a number,
 * which is why the two folders come out of `discover()` with zero frames and
 * have never been in `sheets.generated.ts`.
 *
 * So they ship as nine loose files under `public/present/`, exactly as
 * `public/anim/` holds the effect sheets and for the same reason: 19 kB of WebP
 * against 46 kB of source PNG, fetched by the browser the first time somebody
 * actually throws something and never before. Importing them through Vite
 * instead would inline all nine — every one is under the 4 kB inline limit —
 * and put 26 kB of base64 into the room chunk whether or not a table ever sees
 * a flower.
 *
 * Provenance: the same `image/` tree the build already ships 313 rasters from,
 * and the same tree `build-anim.mjs` packs its 37 effect sheets out of. This
 * adds no set that was not already in the shipped corpus. It deliberately does
 * NOT bring the matching sounds — `audio/system/{egg,flower,fly}{1,2}.mp3` each
 * carry an intact `copyright=绯雨音乐` tag. See
 * `src/room/assets/audio/build-audio.mjs`. The throw's noise is synthesised.
 *
 * Output is committed, for the same reason `public/anim/` and `public/fonts/`
 * are: reproducing it needs the FreeKill checkout and `cwebp`, and `npm
 * install` has neither.
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const WEB_ROOT = resolve(HERE, '..', '..', '..', '..');
const OUT_DIR = join(WEB_ROOT, 'public', 'present');

const argv = process.argv.slice(2);
const flag = (name, fallback) => {
  const hit = argv.find((a) => a === `--${name}` || a.startsWith(`--${name}=`));
  if (!hit) return fallback;
  const [, v] = hit.split('=');
  return v === undefined ? true : v;
};

const FK_ROOT = resolve(String(flag('fk', process.env.FK_ROOT ?? '/Users/haoming/FreeKill')));
/** Matches `build-anim.mjs`: soft-edged art over transparency, where 78/90 is
 *  indistinguishable from 90/100 at the size a seat renders it. */
const QUALITY = Number(flag('q', 78));
const ALPHA_QUALITY = Number(flag('alpha-q', 90));

/** source (under `image/anim/`) -> the name the runtime imports. */
const FRAMES = [
  ['egg/egg.png', 'egg-shot.webp'],
  ['egg/egg1.png', 'egg-hit1.webp'],
  ['egg/egg2.png', 'egg-hit2.webp'],
  ['egg/egg3.png', 'egg-hit3.webp'],
  ['flower/egg.png', 'flower-shot.webp'],
  ['flower/egg1.png', 'flower-hit1.webp'],
  ['flower/egg2.png', 'flower-hit2.webp'],
  ['flower/egg3.png', 'flower-hit3.webp'],
  ['flower/star.png', 'flower-star.webp'],
];

/** PNG: signature, IHDR length+type, then width and height as big-endian u32. */
function pngSize(file) {
  const buf = readFileSync(file, { length: 33 });
  if (buf.length < 24 || buf.readUInt32BE(0) !== 0x89504e47) return null;
  return { w: buf.readUInt32BE(16), h: buf.readUInt32BE(20) };
}

mkdirSync(OUT_DIR, { recursive: true });

const rows = [];
let png = 0;
let webp = 0;
for (const [src, out] of FRAMES) {
  const from = join(FK_ROOT, 'image', 'anim', src);
  const to = join(OUT_DIR, out);
  const size = pngSize(from);
  if (!size) throw new Error(`not a PNG: ${from}`);
  execFileSync('cwebp', [
    '-quiet', '-q', String(QUALITY), '-alpha_q', String(ALPHA_QUALITY), from, '-o', to,
  ]);
  png += readFileSync(from).length;
  const bytes = readFileSync(to).length;
  webp += bytes;
  rows.push({ out, src, w: size.w, h: size.h, bytes });
}

writeFileSync(join(HERE, 'frames.generated.ts'), `/* GENERATED by src/room/assets/present/build-present.mjs — do not edit.
 *
 * ${FRAMES.length} frames. ${(png / 1024).toFixed(1)} kB of source PNG -> ${(webp / 1024).toFixed(1)} kB of WebP.
 *
 * Geometry and filenames only. The images live in \`public/present/\` and are
 * fetched by URL the first time a present is thrown, so nothing here pulls a
 * byte of art into any chunk.
 */
export interface PresentFrame {
  /** Source under the engine's \`image/anim/\`. */
  readonly src: string;
  readonly w: number;
  readonly h: number;
  readonly bytes: number;
}

export const PRESENT_FRAMES: Readonly<Record<string, PresentFrame>> = {
${rows.map((r) => `  '${r.out}': { src: '${r.src}', w: ${r.w}, h: ${r.h}, bytes: ${r.bytes} },`).join('\n')}
};
`);

console.log(`present: ${FRAMES.length} frames, ${(png / 1024).toFixed(1)} kB PNG -> ${(webp / 1024).toFixed(1)} kB WebP`);
